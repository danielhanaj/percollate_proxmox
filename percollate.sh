const $ = id => document.getElementById(id);
const form = $('form');
const jobBox = $('job');
const download = $('download');
let pollTimer = null;

function setStatus(msg, isError = false) {
	const el = $('status');
	el.textContent = msg || '';
	el.classList.toggle('error', isError);
}

function parseUrls(text) {
	const seen = new Set();
	const out = [];
	for (const raw of text.split(/[\s,;]+/)) {
		const t = raw.trim();
		if (!t || seen.has(t)) continue;
		let u;
		try {
			u = new URL(t.startsWith('//') ? 'https:' + t : t);
		} catch {
			continue;
		}
		if (u.protocol !== 'http:' && u.protocol !== 'https:') continue;
		seen.add(t);
		out.push(u.href);
	}
	return out;
}

function headers() {
	const h = { 'Content-Type': 'application/json' };
	const token = $('token').value.trim();
	if (token) h['Authorization'] = 'Bearer ' + token;
	return h;
}

async function api(path, method, body) {
	const res = await fetch(path, {
		method,
		headers: headers(),
		body: body === undefined ? undefined : JSON.stringify(body)
	});
	const data = await res.json().catch(() => ({}));
	if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
	return data;
}

function stateLabel(state) {
	return state === 'processing'
		? 'working'
		: state === 'done'
		? 'done'
		: state;
}

function renderJob(job) {
	$('jobTitle').textContent = `${stateLabel(job.state)} · ${job.format.toUpperCase()} · ${job.urls.length} URL(s)`;
	$('jobState').textContent = job.state === 'done' ? 'done' : job.state === 'error' ? 'error' : 'working';
	$('jobState').className = 'chip ' + job.state;
	$('log').textContent = job.logs.slice(-200).join('\n');
	if (job.state === 'done' && job.output) {
		download.href = job.output.url;
		download.textContent = `Download ${job.output.filename} (${fmtBytes(job.output.bytes)})`;
		download.classList.remove('hidden');
		setStatus(`Finished in ${fmtSec(job.finishedAt - job.startedAt)}`);
		clearInterval(pollTimer);
	} else if (job.state === 'error') {
		download.classList.add('hidden');
		setStatus(job.error || 'Conversion failed', true);
		clearInterval(pollTimer);
	}
	jobBox.classList.remove('hidden');
	jobBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

function fmtBytes(n) {
	if (n < 1024) return n + ' B';
	if (n < 1024 * 1024) return (n / 1024).toFixed(1) + ' KB';
	return (n / 1024 / 1024).toFixed(1) + ' MB';
}

function fmtSec(ms) {
	const s = Math.round(ms / 1000);
	if (s < 60) return s + 's';
	return Math.floor(s / 60) + 'm ' + (s % 60) + 's';
}

function poll(id) {
	pollTimer = setInterval(async () => {
		try {
			const { job } = await api(`/api/jobs/${id}`);
			renderJob(job);
		} catch (err) {
			clearInterval(pollTimer);
			setStatus(err.message, true);
		}
	}, 1300);
}

