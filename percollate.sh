/*
 * percollate-web — web GUI for percollate.
 *
 * Pure Node (node:http), zero npm runtime dependencies.
 * percollate lives in the base image at /node_modules and is imported by
 * worker.js (a child process) so a crashed renderer never takes down the API.
 */
import http from 'node:http';
import fsp from 'node:fs/promises';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const PUBLIC_DIR = path.join(__dirname, 'public');
const WORKER_PATH = path.join(__dirname, 'worker.js');

const PORT = Number(process.env.PORT || 8080);
const OUTPUT_DIR = path.resolve(process.env.OUTPUT_DIR || '/web-out');
const MAX_CONCURRENT = Number(process.env.MAX_CONCURRENT || 2);
const WORKER_TIMEOUT_SECONDS = Number(process.env.WORKER_TIMEOUT_SECONDS || 300);
const CLEANUP_TTL_MINUTES = Number(process.env.CLEANUP_TTL_MINUTES || 60);
const API_TOKEN = process.env.API_TOKEN || null;
const ALLOWED_ORIGINS = (process.env.ALLOWED_ORIGINS || '')
	.split(',')
	.map(s => s.trim().toLowerCase())
	.filter(Boolean);
const NO_SANDBOX = process.env.NO_SANDBOX === '1';

const FORMATS = ['pdf', 'epub', 'html', 'md'];
const EXT = { pdf: 'pdf', epub: 'epub', html: 'html', md: 'md' };
const MAX_BODY_BYTES = 1_000_000;
const CORS = 'same-origin';

const MIME = {
	'.html': 'text/html; charset=utf-8',
	'.js': 'text/javascript; charset=utf-8',
	'.css': 'text/css; charset=utf-8',
	'.json': 'application/json; charset=utf-8',
	'.svg': 'image/svg+xml',
	'.png': 'image/png',
	'.ico': 'image/x-icon',
	'.txt': 'text/plain; charset=utf-8'
};

let percollateVersion = null;
try {
	percollateVersion = require('percollate/package.json').version;
} catch {
	/* health endpoint reports unknown */
}

const jobs = new Map();
const queue = [];
let active = 0;

await fsp.mkdir(OUTPUT_DIR, { recursive: true });

function sendJSON(res, code, obj) {
	const body = JSON.stringify(obj, null, 2);
	res.writeHead(code, {
		'Content-Type': MIME['.json'],
		'Cache-Control': 'no-store'
	});
	res.end(body);
}

function auth(req) {
	if (!API_TOKEN) return true;
	const h = req.headers.authorization || '';
	return h === `Bearer ${API_TOKEN}`;
}

function validUrl(raw) {
	let u;
	try {
		u = new URL(raw.trim());
	} catch {
		return null;
	}
	if (u.protocol !== 'http:' && u.protocol !== 'https:') return null;
	if (ALLOWED_ORIGINS.length && !ALLOWED_ORIGINS.includes(u.hostname)) return null;
	return u.href;
}

function sanitizeOptions(o) {
	const opt = { ...(o || {}) };
	const names = new Set([
		'title', 'author', 'individual', 'inline', 'toc', 'toc-level',
		'hyphenate', 'cover', 'css', 'wait', 'amp', 'unsafe', 'debug', 'sandbox'
	]);
	for (const k of Object.keys(opt)) {
		if (!names.has(k)) delete opt[k];
	}
	if (NO_SANDBOX) opt.sandbox = false;
	return opt;
}

function pushLog(job, line) {
	line = String(line).trim();
	if (!line) return;
	job.logs.push(line);
	if (job.logs.length > 300) job.logs = job.logs.slice(-300);
}

function createJob(spec) {
	const id = randomUUID().replaceAll('-', '').slice(0, 12);
	const job = {
		id,
		state: 'queued',
		format: spec.format,
		urls: spec.urls,
		options: spec.options,
		createdAt: Date.now(),
		startedAt: null,
		finishedAt: null,
		logs: [],
		output: null,
		error: null
	};
	jobs.set(id, job);
	queue.push(job);
	pump();
	return job;
}

function pump() {
	while (active < MAX_CONCURRENT && queue.length) {
		const job = queue.shift();
		active++;
		run(job).finally(() => {
			active--;
			pump();
		});
	}
}

function run(job) {
	return new Promise(resolve => {
		job.state = 'processing';
		job.startedAt = Date.now();
		pushLog(job, `Starting ${job.format.toUpperCase()} for ${job.urls.length} URL(s)`);

		const outPath = path.join(OUTPUT_DIR, `${job.id}.${EXT[job.format]}`);
		const spec = {
			id: job.id,
			format: job.format,
			urls: job.urls,
			options: { ...job.options, output: outPath }
		};

		const child = spawn(process.execPath, [WORKER_PATH], {
			stdio: ['pipe', 'pipe', 'pipe']
		});

		const timer = setTimeout(() => {
			child.kill('SIGKILL');
		}, WORKER_TIMEOUT_SECONDS * 1000);

		let result = null;

		const onData = chunk => {
			for (const line of chunk.toString().split('\n')) {
				const t = line.trim();
				if (!t) continue;
				if (t.startsWith('{"ok"')) {
					try {
						result = JSON.parse(t);
					} catch {
						/* ignore */
					}
				} else {
					pushLog(job, t);
				}
			}
		};

		child.stdout.on('data', onData);
		child.stderr.on('data', onData);

		child.on('error', err => {
			clearTimeout(timer);
			job.state = 'error';
			job.error = err.message;
			pushLog(job, `Failed to start worker: ${err.message}`);
		});

		child.on('close', async code => {
			clearTimeout(timer);
			job.finishedAt = Date.now();
			if (result?.ok === true) {
				const stat = await fsp.stat(outPath).catch(() => null);
				job.output = {
					filename: path.basename(outPath),
					bytes: stat?.size || 0,
					url: `/api/jobs/${job.id}/download`
				};
				job.state = 'done';
				pushLog(job, 'Done.');
			} else {
				job.state = 'error';
				job.error =
					result?.error || `Worker exited with status ${String(code)}`;
				pushLog(job, job.error);
			}
			resolve();
		});

		child.stdin.write(JSON.stringify(spec));
		child.stdin.end();
	});
}

async function readBody(req) {
	const chunks = [];
	let size = 0;
	for await (const chunk of req) {
		size += chunk.length;
		if (size > MAX_BODY_BYTES) {
			const err = new Error('Request body too large');
			err.status = 413;
			throw err;
		}
		chunks.push(chunk);
	}
	const raw = Buffer.concat(chunks).toString('utf8');
	if (!raw) return {};
	try {
		return JSON.parse(raw);
	} catch {
		const err = new Error('Invalid JSON body');
		err.status = 400;
		throw err;
	}
}

function serveFile(res, filePath) {
	fs.createReadStream(filePath)
		.on('error', () => sendJSON(res, 404, { error: 'Not found' }))
		.pipe(res);
}

function handleStatic(req, res, pathname) {
	let rel = pathname === '/' ? '/index.html' : pathname;
	const filePath = path.normalize(path.join(PUBLIC_DIR, rel));
	if (!filePath.startsWith(PUBLIC_DIR)) {
		return sendJSON(res, 403, { error: 'Forbidden' });
	}
	return fsp.stat(filePath).then(
		stat => {
			if (!stat.isFile()) return sendJSON(res, 404, { error: 'Not found' });
			const type = MIME[path.extname(filePath)] || 'application/octet-stream';
			res.writeHead(200, { 'Content-Type': type, 'X-Content-Type-Options': 'nosniff' });
			serveFile(res, filePath);
		},
		() => sendJSON(res, 404, { error: 'Not found' })
	);
}

function jobJSON(job) {
	return {
		id: job.id,
		state: job.state,
		format: job.format,
		urls: job.urls,
		options: job.options,
		createdAt: job.createdAt,
		startedAt: job.startedAt,
		finishedAt: job.finishedAt,
		logs: job.logs,
		output: job.output,
		error: job.error
	};
}

async function route(req, res) {
	const u = new URL(req.url, 'http://localhost');
	const pathname = decodeURIComponent(u.pathname);

	if (pathname.startsWith('/api/')) {
		if (!auth(req)) return sendJSON(res, 401, { error: 'Unauthorized' });

		if (req.method === 'GET' && pathname === '/api/health') {
			return sendJSON(res, 200, {
				ok: true,
				service: 'percollate-web',
				percollate: percollateVersion,
				concurrency: { active, limit: MAX_CONCURRENT },
				queueDepth: queue.length
			});
		}

		if (req.method === 'POST' && pathname === '/api/convert') {
			const body = await readBody(req);
			const format = String(body.format || '').toLowerCase();
			if (!FORMATS.includes(format)) {
				return sendJSON(res, 400, { error: `format must be one of: ${FORMATS.join(', ')}` });
			}
			const rawUrls = Array.isArray(body.urls) ? body.urls : [];
			const urls = [];
			for (const raw of rawUrls) {
				const ok = validUrl(String(raw));
				if (!ok) {
					return sendJSON(res, 400, { error: `Invalid or disallowed URL: ${String(raw)}` });
				}
				urls.push(ok);
			}
			if (!urls.length) {
				return sendJSON(res, 400, { error: 'Provide at least one valid http(s) URL' });
			}
			const job = createJob({ format, urls, options: sanitizeOptions(body.options) });
			res.writeHead(202, { 'Content-Type': MIME['.json'], 'Cache-Control': 'no-store' });
			res.end(JSON.stringify({ job: jobJSON(job) }, null, 2));
			return;
		}

		const m = pathname.match(/^\/api\/jobs\/([0-9a-f]{12})$/);
		if (m && req.method === 'GET') {
			const job = jobs.get(m[1]);
			if (!job) return sendJSON(res, 404, { error: 'No such job (expired?). Restart conversion.' });
			return sendJSON(res, 200, { job: jobJSON(job) });
		}

		const d = pathname.match(/^\/api\/jobs\/([0-9a-f]{12})\/download$/);
		if (d && req.method === 'GET') {
			const job = jobs.get(d[1]);
			if (!job) {
				return sendJSON(res, 404, { error: 'No such job (expired?). Restart conversion.' });
			}
			if (job.state !== 'done' || !job.output) {
				return sendJSON(res, 409, { state: job.state, error: 'File not ready yet' });
			}
			const filePath = path.join(OUTPUT_DIR, job.output.filename);
			const stat = await fsp.stat(filePath).catch(() => null);
			if (!stat) return sendJSON(res, 410, { error: 'Output file expired or missing' });
			res.writeHead(200, {
				'Content-Type': 'application/octet-stream',
				'Content-Length': stat.size,
				'Content-Disposition': `attachment; filename="${job.output.filename}"`,
				'Cache-Control': 'no-store'
			});
			serveFile(res, filePath);
			return;
		}

		return sendJSON(res, 404, { error: 'Not found' });
	}

	return handleStatic(req, res, pathname);
}

const server = http.createServer(async (req, res) => {
	try {
		await route(req, res);
	} catch (err) {
		const status = err.status || 500;
		sendJSON(res, status, { error: status === 500 ? 'Internal server error' : err.message });
	}
});

server.listen(PORT, '0.0.0.0', () => {
	process.stdout.write(`percollate-web listening on http://0.0.0.0:${PORT}\n`);
});

setInterval(() => {
	const now = Date.now();
	for (const job of jobs.values()) {
		if (job.state !== 'done' && job.state !== 'error') continue;
		if (now - job.finishedAt > CLEANUP_TTL_MINUTES * 60_000) {
			const filePath = job.output ? path.join(OUTPUT_DIR, job.output.filename) : null;
			jobs.delete(job.id);
			if (filePath) fsp.unlink(filePath).catch(() => {});
		}
	}
}, 5 * 60_000).unref();

function shutdown() {
	process.stdout.write('\nShutting down…\n');
	server.close(() => process.exit(0));
	setTimeout(() => process.exit(0), 2000).unref();
}
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);
