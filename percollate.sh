			.map(f => {
				const base = path.basename(f, ext).slice(prefix.length);
				const target = uniqueName(dir, slugifyTitle(base) || jobBase, ext);
				fs.renameSync(path.join(dir, f), path.join(dir, target));
				return target;
			});
		if (renamed.length) filename = renamed[0];
