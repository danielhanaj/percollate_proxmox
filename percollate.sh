async function route(req, res) {
	const u = new URL(req.url, 'http://localhost');
	const pathname = decodeURIComponent(u.pathname);

	if (pathname.startsWith('/api/')) {
		if (!auth(req)) return sendJSON(res, 401, { error: 'Unauthorized' });

		if (req.method === 'GET' && pathname === '/api/health') {
			return sendJSON(res, 200, {
				ok: true,
				service: 'percollate-web',
				percollate: percollateVersion,
				concurrency: { active, limit: MAX_CONCURRENT },
				queueDepth: queue.length
			});
		}

		if (req.method === 'POST' && pathname === '/api/convert') {
			const body = await readBody(req);
			const format = String(body.format || '').toLowerCase();
			if (!FORMATS.includes(format)) {
				return sendJSON(res, 400, { error: `format must be one of: ${FORMATS.join(', ')}` });
			}
			const rawUrls = Array.isArray(body.urls) ? body.urls : [];
			const urls = [];
			for (const raw of rawUrls) {
				const ok = validUrl(String(raw));
				if (!ok) {
					return sendJSON(res, 400, { error: `Invalid or disallowed URL: ${String(raw)}` });
				}
				urls.push(ok);
			}
			if (!urls.length) {
				return sendJSON(res, 400, { error: 'Provide at least one valid http(s) URL' });
			}
			const job = createJob({ format, urls, options: sanitizeOptions(body.options) });
			res.writeHead(202, { 'Content-Type': MIME['.json'], 'Cache-Control': 'no-store' });
			res.end(JSON.stringify({ job: jobJSON(job) }, null, 2));
			return;
		}

		const m = pathname.match(/^\/api\/jobs\/([0-9a-f]{12})$/);
		if (m && req.method === 'GET') {
			const job = jobs.get(m[1]);
			if (!job) return sendJSON(res, 404, { error: 'No such job (expired?). Restart conversion.' });
			return sendJSON(res, 200, { job: jobJSON(job) });
		}

		const d = pathname.match(/^\/api\/jobs\/([0-9a-f]{12})\/download$/);
		if (d && req.method === 'GET') {
			const job = jobs.get(d[1]);
			if (!job) {
				return sendJSON(res, 404, { error: 'No such job (expired?). Restart conversion.' });
			}
			if (job.state !== 'done' || !job.output) {
				return sendJSON(res, 409, { state: job.state, error: 'File not ready yet' });
			}
			const filePath = path.join(OUTPUT_DIR, job.output.filename);
			const stat = await fsp.stat(filePath).catch(() => null);
			if (!stat) return sendJSON(res, 410, { error: 'Output file expired or missing' });
			res.writeHead(200, {
				'Content-Type': 'application/octet-stream',
				'Content-Length': stat.size,
				'Content-Disposition': `attachment; filename="${job.output.filename}"`,
				'Cache-Control': 'no-store'
			});
			serveFile(res, filePath);
			return;
		}

		return sendJSON(res, 404, { error: 'Not found' });
	}

	return handleStatic(req, res, pathname);
}

